const {_electron:electron}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
(async()=>{
  const directory=await fs.mkdtemp(path.join(os.tmpdir(),'quota-design-'));
  const env={...process.env,QUOTA_TEST_DATA:directory};delete env.ELECTRON_RUN_AS_NODE;
  const executablePath=process.env.QUOTA_PACKAGED_EXE;
  const app=await electron.launch({...(executablePath?{executablePath}:{}),args:[...(executablePath?[]:['.']),'--demo','--test-mode'],env});
  try{
    const page=await app.firstWindow();await page.locator('#mini-codex').filter({hasText:'12%'}).waitFor();
    assert.equal(await page.evaluate(async()=>{await document.fonts.ready;return document.fonts.check('16px Inter');}),true);
    await page.locator('#toggle').click();
    const fit=await page.locator('.panel-body').evaluate(el=>({visible:el.clientHeight,content:el.scrollHeight}));
    assert.ok(fit.content<=fit.visible+1,`Reference cards must fit without scrolling: ${JSON.stringify(fit)}`);
    assert.equal(await page.locator('.bar').isVisible(),false);
    const labels=await page.locator('.quota-number').allTextContents();assert.deepEqual(labels,['36%','57%','62%','88%','12%']);
    const fills=await page.locator('.track').evaluateAll(nodes=>nodes.map(el=>({value:Number(el.getAttribute('aria-valuenow')),fill:el.firstElementChild.getBoundingClientRect().width/el.getBoundingClientRect().width*100})));
    for(const row of fills)assert.ok(Math.abs(row.value-row.fill)<1,'Bar length and numerical percentage must agree');
    const iconStatus=await page.locator('.provider-icon img').evaluateAll(images=>images.every(image=>image.complete&&image.naturalWidth>0));assert.equal(iconStatus,true);
    await fs.mkdir('test-results',{recursive:true});await page.mouse.move(0,0);await page.screenshot({path:'test-results/design-expanded.png'});
    await page.locator('.card.claude .connection-status').click();
    assert.equal(await page.locator('.card.claude .connection-steps li.done').count(),4);
    await page.locator('.card.claude .auth-message.success').waitFor();
    await page.locator('.card.claude').screenshot({path:'test-results/design-connection.png'});
    await page.locator('.card.claude .close-connection').click();await page.locator('#collapse').click();
    await page.screenshot({path:'test-results/design-compact.png'});
    const baseline=await page.evaluate(()=>window.quota.getState());
    const send=state=>app.evaluate(({BrowserWindow},snapshot)=>BrowserWindow.getAllWindows()[0].webContents.send('state',snapshot),state);
    const unsigned=structuredClone(baseline);unsigned.providers.claude.status='signed_out';unsigned.providers.claude.reading=null;unsigned.providers.claude.error='請完成帳號連接';
    await send(unsigned);await page.locator('#mini-claude').filter({hasText:'未連接'}).waitFor();
    await page.screenshot({path:'test-results/design-unsigned.png'});
    const stale=structuredClone(baseline);stale.providers.codex.status='stale';stale.providers.codex.error='暫時無法連線';
    await send(stale);await page.locator('#mini-codex').filter({hasText:'更新失敗'}).waitFor();
    assert.equal(await page.locator('#window-codex').textContent(),'12%');
    assert.match(await page.locator('#window-codex').getAttribute('aria-label'),/上次資料/);
    await page.screenshot({path:'test-results/design-stale.png'});
    await page.evaluate(()=>window.quota.expand(true));
    const limited=structuredClone(baseline);limited.expanded=true;limited.providers.claude.status='unavailable';limited.providers.claude.reading=null;
    limited.providers.claude.error='Claude 配額服務限制查詢頻率（HTTP 429）';limited.providers.claude.nextPollAt=Date.now()+3600000;
    await send(limited);await page.locator('.card.claude .status-label').filter({hasText:'服務限流'}).waitFor();
    assert.match(await page.locator('.card.claude .empty-message').textContent(),/1 小時.*自動重試/);
    assert.equal(await page.locator('.card.claude .connect-primary').isDisabled(),true);
    const limitFits=await page.locator('.panel-body').evaluate(el=>el.scrollHeight<=el.clientHeight+1);
    assert.equal(limitFits,true,'A cooled-down provider must not push the other live quota cards out of view');
    await page.locator('.card.claude').screenshot({path:'test-results/design-rate-limit.png'});
    const report={passed:true,packaged:!!executablePath,checks:['bundled Inter font','reference card values and layout','three cards fit without scrollbar','expanded panel hides compact bar','bars match percentage values','vector icons load','four completed connection stages','connected success banner','explicit signed-out compact state','stale compact state retains labeled old value'],layout:fit};
    await fs.writeFile('test-results/design.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
  }finally{await app.close();await fs.rm(directory,{recursive:true,force:true,maxRetries:5,retryDelay:200});}
})().catch(e=>{console.error(e);process.exitCode=1;});
